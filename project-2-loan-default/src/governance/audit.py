"""
Automated Regulatory Governance & Auditing Engine - Project 2
Compiles statistical evaluation and drift metrics into a formal Markdown Model Card.
"""

import json
import sys
from pathlib import Path

GOV_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = GOV_DIR.parents[1]
sys.path.append(str(PROJECT_ROOT))


def compile_compliance_audit():
    """Reads runtime JSON metrics and auto-generates an accurate Markdown Model Card report."""
    artifacts_dir = PROJECT_ROOT / "artifacts"
    docs_dir = PROJECT_ROOT / "docs"

    eval_report_path = artifacts_dir / "compliance_audit_report.json"
    drift_report_path = artifacts_dir / "data_drift_report.json"
    model_card_path = docs_dir / "model_card.md"

    print("🔍 Inspecting performance and drift artifacts for regulatory review...")

    eval_data = {}
    if eval_report_path.exists():
        with open(eval_report_path, "r", encoding="utf-8") as f:
            eval_data = json.load(f)

    drift_data = {}
    drift_report_exists = drift_report_path.exists()
    if drift_report_exists:
        with open(drift_report_path, "r", encoding="utf-8") as f:
            drift_data = json.load(f)

    fairness_block = eval_data.get("fairness_metrics", {})
    perf_block = eval_data.get("performance_metrics", eval_data.get("metrics", {}))

    fairness_status = fairness_block.get("demographic_parity_status", "UNKNOWN")
    disparate_impact_ratio = fairness_block.get("disparate_impact_ratio", "N/A")

    test_auc = perf_block.get("test_roc_auc", perf_block.get("roc_auc", "N/A"))
    test_acc = perf_block.get("test_accuracy", perf_block.get("accuracy", "N/A"))
    test_logloss = perf_block.get("log_loss", "N/A")

    if not drift_report_exists:
        drift_status = "UNKNOWN (NO_DRIFT_REPORT)"
    elif drift_data.get("drift_detected_alert") is True:
        drift_status = "DRIFT DETECTED"
    else:
        drift_status = drift_data.get("overall_status", "STABLE")

    markdown_content = f"""# 📑 Automated Model Card & Compliance Audit Report
**Project 2: Loan Default Risk Underwriting Engine**

---

## ⚖️ Model Governance & Fairness Summary
* **Demographic Parity Status:** `{fairness_status}`
* **Disparate Impact Ratio (Young `<30` vs. Baseline `>=30`):** `{disparate_impact_ratio}`
* **Mitigation Mechanism:** `Sample Reweighting (Pre-processing Demographic Parity)`

## 📊 Core Holdout Evaluation Metrics
* **Test ROC-AUC:** `{test_auc}`
* **Test Classification Accuracy:** `{test_acc}`
* **Test Log-Loss:** `{test_logloss}`

## 📡 Population Stability & Production Drift
* **Data Distribution Status:** `{drift_status}`
* **Calculated Features Monitored:**
"""

    metrics = drift_data.get("metrics", {})
    if metrics:
        for feature, info in metrics.items():
            markdown_content += f"  * **{feature}:** PSI = `{info.get('psi_value')}` [{info.get('status')}]\n"
    else:
        markdown_content += "  * No live drift telemetry registered.\n"

    markdown_content += """
---
*Report auto-generated by the Automated Governance Engine.*
"""

    docs_dir.mkdir(parents=True, exist_ok=True)
    with open(model_card_path, "w", encoding="utf-8") as f:
        f.write(markdown_content.strip())

    print(
        f"🎉 Governance Audit complete. Updated compliance sheet exported to: {model_card_path}"
    )


if __name__ == "__main__":
    compile_compliance_audit()
